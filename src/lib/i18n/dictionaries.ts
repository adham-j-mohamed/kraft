export const DICTS: Record<Locale, Dict> = { sv, en };

export type Vars = Record<string, string | number>;
export type TFn = (key: Key, vars?: Vars) => string;
export type TnFn = (key: PluralKey, n: number, vars?: Vars) => string;

export function translate(dict: Dict, key: Key, vars?: Vars): string {
  const raw = dict[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

export function makeT(locale: Locale): { t: TFn; tn: TnFn } {
  const dict = DICTS[locale];
  const t: TFn = (key, vars) => translate(dict, key, vars);
  const tn: TnFn = (key, n, vars) => translate(dict, `${key}_${n === 1 ? "one" : "other"}` as Key, { n, ...vars });
  return { t, tn };
}
